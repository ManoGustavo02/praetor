-- Praetor: languages. English and Brazilian Portuguese.
-- Templates use {A} actor, {T} targets, {V} {V2} values, {S} text, {N} number.
-- Other addons can add keys with Praetor.AddPhrases("en", { key = "text" }).
local P = Praetor

P.Lang = P.Lang or { en = {}, pt = {} }

function P.AddPhrases(lang, t)
	P.Lang[lang] = P.Lang[lang] or {}
	for k, v in pairs(t) do P.Lang[lang][k] = v end
end

local function fillLang(lang, text, args)
	if not args then return text end
	return (text:gsub("{(%w+)}", function(k)
		local v = args[k]
		if v == nil then return "" end
		-- "@arg_player": a word to translate too (the server doesn't know your language)
		if isstring(v) and v:sub(1, 1) == "@" and #v > 1 then
			local key = v:sub(2)
			local word = (P.Lang[lang] and P.Lang[lang][key]) or P.Lang.en[key]
			if word then return word end
		end
		if istable(v) then
			if v.n then return tostring(v.n) end
			local names = {}
			for _, x in ipairs(v) do
				if istable(x) then names[#names + 1] = x.all and "*" or tostring(x.n or "?")
				elseif isentity(x) and IsValid(x) and x:IsPlayer() then names[#names + 1] = x:Nick()
				else names[#names + 1] = tostring(x) end
			end
			return table.concat(names, ", ")
		end
		if isentity(v) and IsValid(v) and v:IsPlayer() then return v:Nick() end
		return tostring(v)
	end))
end

-- text in a given language (used by the server for the console)
function P.LText(lang, key, args, fallback)
	local t = (P.Lang[lang] and P.Lang[lang][key]) or P.Lang.en[key] or fallback or key
	return fillLang(lang, t, args)
end

if CLIENT then
	function P.CurrentLang()
		local set = P.Setting and P.Setting("lang") or "auto"
		if set == "en" or set == "pt" then return set end
		local gl = GetConVarString("gmod_language") or ""
		if gl:sub(1, 2):lower() == "pt" then return "pt" end
		return "en"
	end

	-- P.L(key, args, fallback)
	function P.L(key, args, fallback)
		return P.LText(P.CurrentLang(), key, args, fallback)
	end
end

